package com.example.phase2.model;

public class Rate {
    private int id;
    private int outOfFive;

    public Rate() {
        this.id = id;
        this.outOfFive = outOfFive;
    }

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public int getOutOfFive() {
        return outOfFive;
    }

    public void setOutOfFive(int outOfFive) {
        this.outOfFive = outOfFive;
    }
}
